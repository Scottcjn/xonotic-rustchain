def generate() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    write_textures()
    write_material_file(SOURCE_MTL_FILE)
    mesh = build_mesh()
    mesh.write(SOURCE_OBJ_FILE, SOURCE_MTL_FILE.name)
    write_iqm_direct(MODEL_FILE, mesh)
    write_skin()
    write_preview()
    (OUT / "README.md").write_text(README_TEXT, encoding="utf-8")
    (OUT / "LICENSE").write_text(LICENSE_TEXT, encoding="utf-8")


if __name__ == "__main__":
    generate()
    print(f"Wrote {PROP_NAME} prop package to {OUT}")
