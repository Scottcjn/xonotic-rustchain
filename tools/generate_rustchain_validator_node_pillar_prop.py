def write_material_file(path: Path) -> None:
    lines: list[str] = []
    for material, spec in MATERIALS.items():
        kd = spec["kd"]
        lines.extend(
            [
                f"newmtl {material}",
                f"Kd {kd[0]:.3f} {kd[1]:.3f} {kd[2]:.3f}",
                f"map_Kd {spec['texture']}",
                "",
            ]
        )
    path.write_text("\n".join(lines), encoding="ascii")


def build_mesh() -> ObjBuilder:
    mesh = ObjBuilder()
    mesh.add_cylinder((0, 0, 0.12), 1.15, 0.24, 8, "pillar_metal", "pillar_gold", phase=math.pi / 8)
    mesh.add_cylinder((0, 0, 0.30), 0.92, 0.12, 8, "pillar_gold", "pillar_gold", phase=math.pi / 8)
    mesh.add_box((0, 0, 1.08), (0.62, 0.62, 1.58), "pillar_metal")
    mesh.add_box((0.325, 0, 1.08), (0.045, 0.44, 1.32), "pillar_glow")
    mesh.add_box((-0.325, 0, 1.08), (0.045, 0.44, 1.32), "pillar_glow")
    mesh.add_box((0, 0.325, 1.08), (0.44, 0.045, 1.32), "pillar_glow")
    mesh.add_box((0, -0.325, 1.08), (0.44, 0.045, 1.32), "pillar_glow")
    for x in (-0.43, 0.43):
        for y in (-0.43, 0.43):
            mesh.add_box((x, y, 1.06), (0.10, 0.10, 1.38), "pillar_gold")
    mesh.add_cylinder((0, 0, 1.55), 0.68, 0.06, 16, "pillar_glass", "pillar_glass")
    mesh.add_cylinder((0, 0, 1.94), 0.76, 0.16, 12, "pillar_metal", "pillar_gold", phase=math.pi / 12)
    mesh.add_cylinder((0, 0, 2.09), 0.48, 0.08, 24, "pillar_gold", "pillar_gold")
    mesh.add_cylinder((0, 0, 2.18), 0.34, 0.06, 24, "pillar_glow", "pillar_glow")
    for x, y in ((0.0, 0.62), (0.0, -0.62), (0.62, 0.0), (-0.62, 0.0)):
        mesh.add_box((x, y, 2.13), (0.07, 0.07, 0.36), "pillar_glow")
    return mesh


