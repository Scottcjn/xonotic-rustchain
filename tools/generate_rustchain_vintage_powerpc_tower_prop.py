    write_texture("powerpc_dark.tga", (28, 30, 32), (78, 84, 86))
    write_texture("powerpc_glow.tga", (10, 39, 43), (31, 216, 224))
    write_texture("powerpc_label.tga", (220, 152, 52), (255, 232, 142))


