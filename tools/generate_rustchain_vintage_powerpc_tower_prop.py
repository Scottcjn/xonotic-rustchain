def write_mtl() -> None:
    lines = ["# Material table for rustchain_vintage_powerpc_tower"]
    for name, material in MATERIALS.items():
        kd = material["kd"]
        lines.extend(
            [
                f"newmtl {name}",
                "Ka 0.000 0.000 0.000",
                "Kd {:.3f} {:.3f} {:.3f}".format(*kd),
                "Ks 0.050 0.050 0.050",
                "Ns 16.0",
                f"map_Kd {material['texture']}",
                "",
            ]
        )
    MTL_FILE.write_text("\n".join(lines), encoding="ascii")


def write_skin() -> None:
    lines = [
        f"{name},models/props/{PROP_NAME}/{material['texture']}"
        for name, material in MATERIALS.items()
    ]
    SKIN_FILE.write_text("\n".join(lines) + "\n", encoding="ascii")


