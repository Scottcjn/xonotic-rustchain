def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    TEXTURES.mkdir(parents=True, exist_ok=True)
    write_textures()
    mesh = build_mesh()
    mesh.write_obj(OBJ_FILE)
    write_mtl()
    write_skin()
    write_preview()
    (OUT / "README.md").write_text(README_TEXT, encoding="utf-8")
    (OUT / "LICENSE").write_text(LICENSE_TEXT, encoding="utf-8")
    print(f"Wrote prop source package to {OUT}")
    print(f"Convert OBJ to IQM separately: {IQM_FILE}")


if __name__ == "__main__":
    main()
